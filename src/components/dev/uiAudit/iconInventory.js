/**
 * The icons the app actually imports, and the guard that keeps that true.
 *
 * WHY A LIST RATHER THAN THE LIBRARY
 * lucide-react ships well over a thousand icons. Dumping all of them onto the
 * audit page would be a slower page that answers a question nobody asked —
 * what matters is whether the ~100 icons this product renders survive a theme
 * and sit on the same optical baseline as each other. A wall of unused glyphs
 * hides that.
 *
 * WHY IT IS WRITTEN OUT RATHER THAN ENUMERATED
 * `import * as icons from 'lucide-react'` would defeat tree-shaking and pull
 * the entire library into the chunk — on a page whose stated cost is zero.
 * Named imports keep the chunk to what is drawn.
 *
 * WHY THAT IS SAFE
 * `test:ui-audit-icons` re-derives this list from the source tree and fails on
 * any difference. A list that silently falls behind the codebase is worse than
 * no list: the page keeps rendering, and the icon someone just added — the one
 * most likely to be off-weight or off-baseline — is the one it does not show.
 *
 * Regenerating after the guard fails is mechanical: the failure message names
 * every icon added and removed.
 *
 * NOTE the Heroicons set is NOT listed here. Those come through the app's own
 * barrel (src/components/ui/icons.js), which the audit page enumerates with
 * `import * as` — that barrel is a fixed module the app already loads whole,
 * so enumerating it costs nothing and cannot drift.
 */
