// Reverse of the createAssessment payload: map a stored assessment doc back
// onto the studio's `form` shape so editing reopens with every paper-level
// field (cover toggles, MCQ layout, import metadata) intact.
// Only defined keys are returned so the caller can spread over form defaults.
function mapAssessmentToForm(a = {}) {
  const out = {}
  const copy = (key, transform) => {
    if (a[key] !== undefined && a[key] !== null) out[key] = transform ? transform(a[key]) : a[key]
  }
  copy('title')
  if (a.subject != null) out.subject = normalizeSubject(a.subject)
  copy('grade', String)
  copy('term', String)
  copy('year')
  copy('duration')
  copy('topic')
  copy('assessmentType')
  copy('schoolName')
  copy('className')
  copy('paperName')
  copy('assessmentDate')
  copy('coverInstructions')
  copy('endOfPaperText')
  copy('mcqOptionLayout')
  copy('mcqAnswerChoiceCount')
  copy('ungroupedOrder')
  copy('mode')
  copy('importStatus')
  copy('sourceFileName')
  copy('sourceContentType')
  if (Array.isArray(a.importWarnings)) out.importWarnings = a.importWarnings
  for (const key of ['showNameField', 'showDateField', 'showMarksField', 'showClassField']) {
    if (typeof a[key] === 'boolean') out[key] = a[key]
  }
  return out
}

function buildTitleFromForm(form) {
  const gradeWord = GRADE_WORDS[form.grade] || form.grade
  const type = ASSESSMENT_TYPE_LABELS[form.assessmentType] || 'Assessment'
  const termBit = form.term ? `TERM ${form.term}` : ''
  const typeUpper = type.toUpperCase()
  let typeFormatted = typeUpper
  if (form.assessmentType === 'end_of_term' && termBit) {
    typeFormatted = `END OF TERM ${form.term} TEST`
  } else if (form.assessmentType === 'mid_term' && termBit) {
    typeFormatted = `MID-TERM ${form.term} TEST`
  } else if (form.assessmentType === 'mock') {
    typeFormatted = 'MOCK EXAMINATION'
  } else if (form.assessmentType === 'examination' || form.assessmentType === 'exam') {
    // Exam Studio papers are titled as a formal examination — no term prefix,
    // since an exam covers the whole syllabus rather than a single term.
    typeFormatted = 'EXAMINATION'
  } else if (termBit) {
    typeFormatted = `${termBit} ${typeUpper}`
  }
  const year = form.year || new Date().getFullYear()
  return `GRADE ${gradeWord} ${typeFormatted} - ${year}`
}

function buildFooterCode(form) {
  const parts = [
    `G${form.grade || ''}`,
    form.subject || '',
    `Term ${form.term || ''}`,
    String(form.year || new Date().getFullYear()),
  ].filter(Boolean)
  return parts.join('/')
}

function plainTextWordCount(value) {
  const text = toEditableText(value)
  if (!text) return 0
  return text.split(/\s+/).filter(Boolean).length
}

