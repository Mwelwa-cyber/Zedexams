  /* ------------ Create paper with AI ------------ */
  // Receives { blocks, assessment, form: aiPaperForm, mode } from
  // CreatePaperModal: blocks are studio-ready sections/parts from
  // aiPaperToSections. 'replace' swaps the whole paper; 'append' adds
  // after the existing questions (the empty starter section is dropped).
  function handleApplyAiPaper({ blocks, assessment, form: aiPaperForm, mode }) {
    const partOffset = mode === 'append' ? parts.length : 0
    const newParts = blocks.parts.map((p, i) => ({ ...p, order: partOffset + i }))
    // Compute the committed sections array explicitly so the auto-diagram pass
    // can attach images by the same indices that land in state.
    const baseSections = mode === 'replace'
      ? (blocks.sections.length ? blocks.sections : [createStandaloneSection()])
      : (hasOnlyEmptyStarterSection(sections) ? blocks.sections : [...sections, ...blocks.sections])
    setSections(baseSections)
    if (mode === 'replace') {
      setParts(newParts)
    } else {
      setParts(prev => [...prev, ...newParts])
    }
    // Fill paper metadata the teacher hasn't set yet — including their school
    // name from the saved School Profile (falling back to the most recent
    // saved paper), so AI-created papers print with the school header without
    // re-typing it each time.
    const typeMap = {
      topic_test: 'topic', weekly_test: 'weekly',
      mid_term: 'mid_term', end_of_term: 'end_of_term',
      // Exam Studio types are passed through unchanged (the modal already emits
      // the studio's own value for them — see CreatePaperModal).
      mock: 'mock', examination: 'examination', exam: 'exam',
    }
    // The modal now emits a canonical subject KEY ('numeracy',
    // 'integrated_science'); the studio form carries a display label, so map
    // it back to something human-readable for the header/exports.
    const aiSubjectLabel = aiPaperForm.subject
      ? kbSubjectLabel(aiPaperForm.subject) : ''
    setForm(f => {
      const lastWithSchool = recentPapers.find(p => (p.schoolName || '').trim())
      const recentBranding = {
        schoolName: lastWithSchool?.schoolName || '',
      }
      const branding = brandingForAiPaper(f, schoolProfile, recentBranding)
      return {
        ...f,
        // Grade/subject were chosen explicitly in the modal — the paper
        // follows them (unlike the fields below, which only backfill).
        grade: aiPaperForm.grade || f.grade,
        subject: aiSubjectLabel || f.subject,
        term: f.term || aiPaperForm.term,
        duration: f.duration || String(aiPaperForm.durationMinutes),
        assessmentType: typeMap[aiPaperForm.assessmentType] || f.assessmentType,
        coverInstructions: f.coverInstructions ||
          String(assessment?.header?.instructions || ''),
        schoolName: branding.schoolName,
      }
    })
    setCreatePaperOpen(false)
    closeSlide()
    changeView('builder')
    // The applied AI paper is the new undo baseline — not the empty starter.
    resetUndoBaseline()
    const flagged = blocks.warnings.length
    showToast(
      `AI paper ${mode === 'replace' ? 'created' : 'added'} — ` +
      `${blocks.questionCount} questions, ${blocks.totalMarks} marks.` +
      (flagged ? ` ${flagged} flagged for review.` : ' Review before saving.'),
    )
    // Close the diagram loop immediately. With "Draw diagrams automatically"
    // on (the default), generate every figure now; otherwise open the fixup
    // panel so the teacher attaches/generates them in one click rather than
    // discovering gaps at print time.
    if (countDiagramJobs(baseSections) > 0) {
      if (aiPaperForm?.autoDiagrams !== false) {
        runAutoDiagrams(baseSections)
      } else {
        setDiagramFixOpen(true)
      }
    }
  }

  // Attach a picture-bank / AI-generated figure to a diagram-flagged
  // question and clear its "Diagram needed" review note (un-flagging the
  // question entirely when that was the only note). `silent` suppresses the
  // per-attach toast during the automatic batch pass.
  function attachDiagramToSection(sectionIndex, url, { silent = false } = {}) {
    if (!url) return
    updateSection(sectionIndex, section => {
      const remainingNotes = (section.question.reviewNotes || [])
        .filter(n => !String(n).startsWith('Diagram needed:'))
      return {
        ...section,
        question: {
          ...section.question,
          imageUrl: url,
          imageAssetId: '',
          reviewNotes: remainingNotes,
          requiresReview: remainingNotes.length > 0,
        },
      }
    })
    if (!silent) showToast('Diagram attached.')
  }

  // Attach a generated figure to one option of a picture-based MCQ. Clears
  // the slot's pending brief and, once every option has its image, drops the
  // "Picture options needed" review note.
  function attachOptionDiagramToSection(sectionIndex, optionIndex, url) {
    if (!url) return
    updateSection(sectionIndex, section => {
      const existing = Array.isArray(section.question.optionMedia) ? section.question.optionMedia : []
      const next = existing.map(slot => (slot ? { ...slot } : slot))
      const slot = next[optionIndex] || { alt: '' }
      next[optionIndex] = { ...slot, imageUrl: url, alt: slot.alt || '', diagramBrief: '' }
      const stillNeeds = next.some(s => s && s.diagramBrief && !s.imageUrl)
      const remainingNotes = (section.question.reviewNotes || [])
        .filter(n => !String(n).startsWith('Picture options needed'))
      return {
        ...section,
        question: {
          ...section.question,
          optionMedia: next,
          reviewNotes: stillNeeds ? section.question.reviewNotes : remainingNotes,
          requiresReview: stillNeeds ? section.question.requiresReview : remainingNotes.length > 0,
        },
      }
    })
  }

  // Generate every pending figure on a freshly created AI paper, in the
  // background, with a progress banner. Reused implementation lives in
  // utils/autoGenerateDiagrams. Whatever's left (cap/error) opens the panel.
  async function runAutoDiagrams(snapshot) {
    const total = Math.min(countDiagramJobs(snapshot), DIAGRAM_AUTO_CAP)
    if (total === 0) return
    setAutoDiagram({ running: true, done: 0, total })
    const result = await autoGenerateDiagrams(snapshot, {
      provider: 'recraft',
      cap: DIAGRAM_AUTO_CAP,
      attachStem: (i, url) => attachDiagramToSection(i, url, { silent: true }),
      attachOption: (i, oi, url) => attachOptionDiagramToSection(i, oi, url),
      onProgress: ({ done, total: t }) => setAutoDiagram({ running: true, done, total: t }),
    })
    setAutoDiagram({ running: false, done: result.done, total: result.total })
    if (result.error) {
      showToast(`Drew ${result.done}/${result.total} diagrams — ${result.error}`, true)
    } else if (result.done > 0) {
      showToast(`Added ${result.done} diagram${result.done === 1 ? '' : 's'} to the paper.`)
    }
    if (result.remaining > 0) setDiagramFixOpen(true)
    window.setTimeout(() => setAutoDiagram(null), 4000)
  }


  /* ------------ AI generation ------------ */
  async function handleGenerateQuestions(topicOverride) {
    const topic = (topicOverride || aiForm.topic || form.topic || '').trim()
    if (!topic) {
      showToast('Add a topic so Zed can generate questions.', true)
      return
    }
    setAiGenerating(true)
    try {
      const { questions: generated, warning: kbWarning } = await generateAIQuizQuestions({
        subject: form.subject,
        grade: form.grade,
        topic,
        count: aiForm.count,
        type: aiForm.type,
        framework: aiForm.framework,
      })
      const generatedList = Array.isArray(generated) ? generated : []
      const usable = generatedList.filter(q => {
        if (!richTextHasContent(q?.text ?? '')) return false
        const t = q?.type || 'mcq'
        if (t === 'fill_blanks') {
          return Array.isArray(q?.statements)
            && q.statements.some(s => /_{2,}/.test(String(s?.text ?? '')))
        }
        if (t === 'short_answer' || t === 'diagram') {
          return String(q?.correctAnswer ?? '').trim().length > 0
        }
        const opts = Array.isArray(q?.options) ? q.options.filter(o => String(o ?? '').trim()) : []
        return opts.length >= 2
      })
      const nextSections = usable.map(q => buildStandaloneSection({
        ...q,
        options: q.options?.length ? q.options : ['', '', '', ''],
      }))
      if (!nextSections.length) {
        showToast('Zed could not generate questions. Try again.', true)
        return
      }
      setSections(prev => hasOnlyEmptyStarterSection(prev)
        ? nextSections
        : [...prev, ...nextSections])
      if (!form.title.trim()) setF('title', `Grade ${form.grade} ${form.subject} - ${topic}`)
      const skipped = generatedList.length - nextSections.length
      showToast(skipped
        ? `Zed returned ${skipped} incomplete; ${nextSections.length} kept. Review before saving.`
        : `Added ${nextSections.length} AI-generated question${nextSections.length === 1 ? '' : 's'}.`)
      if (kbWarning) setTimeout(() => showToast(kbWarning), 1500)
      closeSlide()
      if (view !== 'builder') changeView('builder')
    } catch (error) {
      showToast(getErrorMessage(error, 'AI generation failed.'), true)
    } finally {
      setAiGenerating(false)
    }
  }

