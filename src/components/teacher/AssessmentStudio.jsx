  /* ------------ validation + save ------------ */
  // Every blocking issue is gathered up-front by `collectQuizIssues`
  // (see validationResult / paperHealth above) and shown together in the
  // paper-health gate, so the teacher fixes them in one pass instead
  // of the old "Save → toast → fix → Save → toast → fix" loop.

  // Uploads in-memory imported image blobs (produced by documentQuizImporter)
  // to Firebase Storage and returns a Map<assetId, downloadUrl>. The kindSlug
  // (e.g. "question", "passage", "option") is interpolated into the filename
  // so we can distinguish where each upload originated when auditing Storage.
  async function uploadImportedAssets(assetIds, kindSlug) {
    const uploadedById = new Map()
    if (!assetIds.length) return uploadedById
    if (!currentUser?.uid) throw new Error('Please sign in before saving imported quiz images.')

    const uploadedRefs = []
    try {
      for (const assetId of assetIds) {
        const asset = importedAssets[assetId]
        if (!asset?.blob) {
          throw new Error('An imported image is no longer available. Please re-import the document.')
        }
        const sourceFile = new File([asset.blob], asset.fileName || `${assetId}.jpg`, {
          type: asset.contentType || 'image/jpeg',
        })
        const uploadBlob = await compressImage(sourceFile)
        const fileName = `${Date.now()}-${kindSlug}-${safeStorageName(assetId)}.jpg`
        const path = `assessment-images/${currentUser.uid}/imports/${fileName}`
        const ref = storageRef(storage, path)
        const snapshot = await uploadBytes(ref, uploadBlob, {
          contentType: 'image/jpeg',
          customMetadata: {
            sourceFileName: form.sourceFileName || '',
            sourcePath: asset.sourcePath || '',
          },
        })
        uploadedRefs.push(snapshot.ref)
        uploadedById.set(assetId, await getDownloadURL(snapshot.ref))
      }
    } catch (error) {
      const { deleteObject } = await import('firebase/storage')
      await Promise.all(uploadedRefs.map(ref =>
        deleteObject(ref).catch(cleanupError => console.warn('Orphaned upload cleanup failed:', cleanupError))
      ))
      throw error
    }

    return uploadedById
  }

  // Phase 3 extends this beyond question.imageAssetId to also walk each
  // question's optionMedia[] so per-option imports survive the save.
  async function uploadImportedQuestionImages(questionsToSave) {
    const assetIds = new Set()
    questionsToSave.forEach(q => {
      if (q.imageAssetId) assetIds.add(q.imageAssetId)
      if (Array.isArray(q.optionMedia)) {
        q.optionMedia.forEach(slot => {
          if (slot && typeof slot === 'object' && slot.imageAssetId) {
            assetIds.add(slot.imageAssetId)
          }
        })
      }
    })
    const uploadedById = await uploadImportedAssets(Array.from(assetIds), 'question')
    if (!uploadedById.size) return questionsToSave
    return questionsToSave.map(q => {
      const next = { ...q }
      const stemUrl = uploadedById.get(q.imageAssetId)
      if (stemUrl) {
        next.imageUrl = stemUrl
        next.imageAssetId = ''
      }
      if (Array.isArray(q.optionMedia)) {
        next.optionMedia = q.optionMedia.map(slot => {
          if (!slot || typeof slot !== 'object') return slot
          const url = slot.imageAssetId ? uploadedById.get(slot.imageAssetId) : null
          if (!url) return slot
          const { imageAssetId: _unused, ...rest } = slot
          return { ...rest, imageUrl: url }
        })
      }
      return next
    })
  }

  // Same shape as uploadImportedQuestionImages, but for the parallel
  // passages[] list. Without this, a passage diagram extracted by the
  // importer would persist as a dead blob: URL after save.
  async function uploadImportedPassageImages(passagesToSave) {
    const assetIds = Array.from(new Set(passagesToSave.map(p => p.imageAssetId).filter(Boolean)))
    const uploadedById = await uploadImportedAssets(assetIds, 'passage')
    if (!uploadedById.size) return passagesToSave
    return passagesToSave.map(p => {
      const uploadedUrl = uploadedById.get(p.imageAssetId)
      if (!uploadedUrl) return p
      return { ...p, imageUrl: uploadedUrl, imageAssetId: '' }
    })
  }

  // Persist the current paper to the teacher's durable library (create or
  // update). Shared by the explicit Save button and the auto-save-on-download
  // path. Does NOT gate on validation, toast, or navigate — callers decide.
  // Returns the assessment id. Uses editId (edit route) or the in-session
  // createdIdRef so repeated saves update one doc instead of duplicating.
  async function persistAssessment() {
    const serialized = serializeQuizSections(sections, parts)
    const questionsForSave = await uploadImportedQuestionImages(serialized.questions)
    const passagesForSave = await uploadImportedPassageImages(serialized.passages)
    // Defensive: catch any blob: URL that slipped through the upload pass
    // before it can land in Firestore and break for every learner.
    assertNoBlobImageUrls(questionsForSave, passagesForSave)
    const totalMarksForSave = questionsForSave.reduce((sum, q) => sum + (q.marks || 1), 0)
    const library = classifyForLibrary({
      libraryType: LIBRARY_TYPES.ASSESSMENTS,
      grade: `Grade ${form.grade}`,
      term: form.term,
      subject: STUDIO_TO_LIBRARY_SUBJECT[form.subject] || form.subject,
      assessmentType: STUDIO_TO_LIBRARY_ASSESSMENT_TYPE[form.assessmentType] || form.assessmentType,
    })
    const finalTitle = form.title.trim() || autoTitle
    // Shared payload for both create and update so an edited paper round-trips
    // every field the builder sets — cover toggles, page breaks, MCQ layout
    // and import metadata included.
    const assessmentPayload = {
      title: finalTitle,
      subject: form.subject,
      grade: form.grade,
      term: form.term,
      year: form.year,
      duration: form.duration,
      topic: form.topic,
      assessmentType: form.assessmentType,
      schoolName: form.schoolName,
      className: form.className,
      paperName: form.paperName,
      assessmentDate: form.assessmentDate,
      coverInstructions: form.coverInstructions,
      showNameField: form.showNameField,
      showDateField: form.showDateField,
      showMarksField: form.showMarksField,
      showClassField: form.showClassField,
      mcqOptionLayout: form.mcqOptionLayout,
      mcqAnswerChoiceCount: form.mcqAnswerChoiceCount,
      ungroupedOrder: form.ungroupedOrder ?? 0,
      endOfPaperText: form.endOfPaperText,
      footerCode,
      passages: passagesForSave,
      pagebreaks: serialized.pagebreaks,
      parts: serialized.parts,
      passageCount: passagesForSave.length,
      totalMarks: totalMarksForSave,
      questionCount: questionsForSave.length,
      // Phase 10: see CreateQuizV2 comment — fresh count, persisted so the
      // badge/chip/banner stay honest as flagged questions get fixed.
      reviewCount: form.mode === 'imported_document'
        ? questionsForSave.filter(q => q.requiresReview).length
        : 0,
      mode: form.mode,
      importStatus: form.mode === 'imported_document'
        ? (questionsForSave.some(q => q.requiresReview) ? 'needs_review' : (form.importStatus || 'success'))
        : form.importStatus,
      sourceFileName: form.sourceFileName,
      sourceContentType: form.sourceContentType,
      importWarnings: form.importWarnings,
      library,
    }

    const targetId = editId || createdIdRef.current
    if (targetId) {
      // updateAssessmentWithQuestions upserts changed questions and deletes
      // the ones removed since load — atomic doc + subcollection update.
      await updateAssessmentWithQuestions(
        targetId,
        { ...assessmentPayload, updatedBy: currentUser.uid },
        questionsForSave,
        deletedIds,
      )
      setDeletedIds([])
    } else {
      const newAssessmentId = await createAssessment({ ...assessmentPayload, createdBy: currentUser.uid })
      await saveAssessmentQuestions(newAssessmentId, questionsForSave)
      // Remember the id so later saves/downloads in this session update the
      // same doc instead of creating duplicates while still on /new. Entry is
      // single-flight (callers gate on the saving/exporting flags), so this
      // plain ref write isn't actually racy.
      // eslint-disable-next-line require-atomic-updates
      createdIdRef.current = newAssessmentId
      // The freshly-created paper now owns its questions; clear the
      // new-paper draft so it doesn't resurrect on the next visit.
      clearAssessmentDraft(currentUser.uid)
      clearAssessmentDraftRemote(currentUser.uid)
    }
    setImportedAssets({})
    // The durable library copy now exists / is updated — reflect that.
    setDirty(false)
    setLibraryDirty(false)
    setSavedToLibrary(true)
    return targetId || createdIdRef.current
  }

  // Single-flight wrapper around persistAssessment, shared by the library
  // autosave, the explicit Save, and the auto-save-on-download. Coalesces
  // concurrent calls onto one in-flight write so a brand-new paper can never be
  // created twice (e.g. an autosave firing the instant the teacher hits Save).
  function runLibraryPersist() {
    if (persistInFlightRef.current) return persistInFlightRef.current
    const p = persistAssessment().finally(() => { persistInFlightRef.current = null })
    persistInFlightRef.current = p
    return p
  }

  // The actual save — persist to the library, confirm, and leave. Gated by the
  // health check below; also called by the health gate's "Save to library"
  // button once the paper is clear of blockers.
  async function persistAndExit() {
    setHealthOpen(false)
    setSaving(true)
    try {
      // Let any in-flight library autosave settle first (it captured slightly
      // older content), then persist the current state fresh — so the explicit
      // Save always writes the very latest edits, not the autosave's snapshot.
      if (persistInFlightRef.current) { try { await persistInFlightRef.current } catch { /* its retry is our save */ } }
      const wasUpdate = Boolean(editId || createdIdRef.current)
      await runLibraryPersist()
      showToast(wasUpdate ? 'Changes saved.' : 'Saved to your library!')
      setTimeout(() => navigate(cfg.routeBase), 900)
    } catch (error) {
      console.error(error)
      showToast(`Failed to save: ${getErrorMessage(error)}`, true)
      setSaving(false)
    }
  }

  async function handleSave() {
    // Open the paper-health gate when anything blocks a clean save, so the
    // teacher sees — and fixes — every issue (plus advisories + the AI check)
    // in one pass instead of bailing on the first error with a toast. A clean
    // paper saves straight away — no nagging modal on the happy path.
    if (!paperHealth.ready) {
      setHealthOpen(true)
      return
    }
    await persistAndExit()
  }

  // Seed the builder from a ready-made template (paperTemplates.js). Replaces
  // the blank canvas; if the teacher already has work, the template is appended
  // after it (mirrors how an AI paper is added in "append" mode).
  function handleApplyTemplate(template) {
    const { sections: tplSections, parts: tplParts, formPatch } = instantiateTemplate(template)
    const empty = hasOnlyEmptyStarterSection(sections)
    const partOffset = empty ? 0 : parts.length
    const orderedParts = tplParts.map((p, i) => ({ ...p, order: partOffset + i }))
    const safeSections = tplSections.length ? tplSections : [createStandaloneSection()]
    setSections(empty ? safeSections : [...sections, ...tplSections])
    setParts(empty ? orderedParts : [...parts, ...orderedParts])
    // Apply the template's suggested duration when it's seeding a fresh paper
    // (replace mode) — the template defines the paper, so its duration should
    // win. When appending to existing work, keep the teacher's own duration.
    // (form.duration always defaults to 60, so the old `form.duration ||
    // formPatch.duration` fallback could never actually apply a template's
    // duration — the template's "90 min"/"30 min" shown on the card was silently
    // dropped and every templated paper stayed at 60.)
    if (formPatch.duration && empty) setF('duration', Number(formPatch.duration))
    setTemplateOpen(false)
    closeSlide()
    changeView('builder')
    // The applied template is the new undo baseline — not the empty starter.
    resetUndoBaseline()
    showToast(`“${template.name}” added — fill in the questions, then save.`)
  }

  /* ------------ export (Word / Print) ------------ */
  // PDF export was removed — html2canvas-based PDFs mangled the paper layout
  // too often. Teachers download Word (.docx) and can "Save as PDF" from Word
  // or the browser Print dialog if they need a PDF.
  async function handleExport(kind, mode = 'paper') {
    if (questionCount === 0) {
      showToast('Add at least one question to export.', true)
      return
    }
    setExporting(true)
    try {
      // Auto-save the paper to the teacher's library before handing over the
      // download, so a downloaded paper is never lost — matching every other
      // studio. Only when it passes the pre-publish checklist (errorCount 0):
      // an incomplete paper still downloads but isn't filed here (the
      // continuous library autosave files it separately). Best-effort and
      // silent — a save failure must not block the download the teacher just
      // asked for. Gated on LIBRARY dirtiness (not the device-draft flag, which
      // the per-keystroke autosave clears) so a re-download always writes the
      // latest edits.
      if (shouldAutosaveOnDownload({
        errorCount,
        libraryDirty,
        hasLibraryDoc: Boolean(editId || createdIdRef.current),
      })) {
        try {
          if (persistInFlightRef.current) { try { await persistInFlightRef.current } catch { /* our write below covers it */ } }
          await runLibraryPersist()
        } catch (saveErr) {
          console.error('Auto-save on download failed', saveErr)
        }
      }
      // Auto-titles (e.g. "Grade 4 Mathematics - Fractions") read well as-is;
      // a custom title gets grade/subject prepended so the file still says
      // what it is. buildAssessmentName handles both.
      const docName = (variant, ext = 'docx') => buildAssessmentName({
        title: assessmentDoc.title,
        grade: assessmentDoc.grade,
        subject: assessmentDoc.subject,
        variant,
        ext,
      })
      // Print uses the browser's own dialog and needs nothing from the docx
      // assembler, so short-circuit before loading it. (answersheet mode always
      // builds a .docx — even on a 'print' kind — matching prior behaviour.)
      if (kind === 'print' && mode !== 'answersheet') {
        window.print()
        return
      }
      // Loaded on demand so the docx assembler stays out of the Studio's
      // initial chunk — it only arrives when a teacher actually exports.
      const { downloadAssessmentDocx, downloadAnswerSheetDocx } = await import('../../utils/assessmentToDocx')
      // Standalone answer sheet (bubble grid) — its own builder, not the
      // full-paper layout.
      if (mode === 'answersheet') {
        await downloadAnswerSheetDocx(assessmentDoc, serializedPreview.questions, docName('Answer Sheet'), { attribution: isFreePlanTeacher({ userProfile, isAdmin }) })
        showToast('Answer sheet download started.')
        return
      }
      if (kind === 'docx') {
        await downloadAssessmentDocx(assessmentDoc, serializedPreview.questions, docName(mode === 'scheme' ? 'Marking Key' : undefined), { mode, attribution: isFreePlanTeacher({ userProfile, isAdmin }) })
        showToast('Word download started.')
      }
    } catch (error) {
      console.error(error)
      showToast(`Export failed: ${getErrorMessage(error)}`, true)
    } finally {
      setExporting(false)
    }
  }

  /* ------------ block picker ------------ */
  function handleBlockPick(blockKey) {
    const baseQuestion = (type, overrides = {}) => buildStandaloneSection({
      type,
      detectedType: type,
      ...overrides,
    })
    let newSection = null
    switch (blockKey) {
      case 'mcq':
        newSection = baseQuestion('mcq', { options: ['', '', '', ''], correctAnswer: 0, marks: 1 })
        break
      case 'short_answer':
        newSection = baseQuestion('short_answer', { options: [], correctAnswer: '', marks: 2 })
        break
      case 'structured':
        newSection = baseQuestion('diagram', { options: [], correctAnswer: '', marks: 5, diagramText: 'Structured response' })
        break
      case 'essay':
        newSection = baseQuestion('essay', { options: [], correctAnswer: '', marks: 6 })
        break
      case 'true_false':
        newSection = baseQuestion('mcq', { options: ['True', 'False', '', ''], correctAnswer: 0, marks: 1 })
        break
      case 'fill_in_blank':
        // Dedicated Fill-in-the-Blanks: an instruction + word bank + a set of
        // A/B/C/D statements, each with its own blank(s). Seeded with 4 empty
        // statements (the most common Zambian test-paper size) so the teacher
        // fills in sentences rather than wiring up the structure.
        newSection = baseQuestion('fill_blanks', {
          options: [],
          correctAnswer: '',
          text: 'Fill in the blanks using the words provided below.',
          wordBank: [],
          wordBankReuse: false,
          statements: [
            { text: '', answers: [''] },
            { text: '', answers: [''] },
            { text: '', answers: [''] },
            { text: '', answers: [''] },
          ],
          marks: 4,
        })
        break
      case 'numeric':
        newSection = baseQuestion('numeric', {
          options: [],
          correctAnswer: '',
          numericTolerance: 0,
          numericUnit: '',
          marks: 1,
        })
        break
      case 'matching':
        // Start with 3 empty pairs and no correct mapping — teachers usually
        // type 4–6 pairs but 3 is enough to show the UI without overwhelming.
        newSection = baseQuestion('matching', {
          options: [],
          correctAnswer: '',
          matchingLeft: ['', '', ''],
          matchingRight: ['', '', ''],
          matchingAnswer: [-1, -1, -1],
          marks: 3,
        })
        break
      case 'sequence':
        // Sequence questions ask the student to put items in order.
        // 4 empty slots is the most common shape (life cycles, process
        // steps, historical events).
        newSection = baseQuestion('sequence', {
          options: [],
          correctAnswer: '',
          sequenceItems: ['', '', '', ''],
          sequenceAnswer: [0, 0, 0, 0],
          marks: 4,
        })
        break
      case 'data_table':
        // Data/Table is structured-with-a-table: the teacher attaches a
        // small data table to a short_answer-style question. Seeded with
        // 2 headers + 3 rows so the editor has visible structure.
        newSection = baseQuestion('short_answer', {
          options: [],
          correctAnswer: '',
          marks: 3,
          tableData: {
            headers: ['Column A', 'Column B'],
            rows: [['', ''], ['', ''], ['', '']],
          },
        })
        break
      case 'draw_label':
        // Draw & Label is a structured question with a blank canvas
        // under the prompt for the student to draw their own diagram.
        // Default canvas is 200pt tall — about a third of an A4 page.
        newSection = baseQuestion('diagram', {
          options: [],
          correctAnswer: '',
          marks: 5,
          diagramText: 'Draw and label',
          drawingHeight: 200,
        })
        break
      case 'passage':
        newSection = createPassageSection()
        break
      case 'map':
        // Map questions are passages whose kind is 'map' — the data model
        // (PASSAGE_KIND_MAP) was already plumbed; this just exposes it as
        // a first-class block type with its own block picker tile.
        newSection = createPassageSection({ passageKind: 'map' })
        break
      case 'diagram_stimulus':
        // Diagram-Based Question: one instruction/stem, then a figure, then
        // follow-up sub-questions underneath (passageKind 'diagram'). This is
        // the correct layout for "Study the diagram below and answer the
        // questions that follow." — the instruction prints first, the diagram
        // next, and the sub-questions below it (not all crammed above it).
        newSection = createPassageSection({
          passageKind: 'diagram',
          title: 'Study the diagram below and answer the questions that follow.',
          questions: [
            { type: 'short_answer', options: [], correctAnswer: '', marks: 1, answerFormat: 'lines', answerLines: 2 },
          ],
        })
        break
      case 'source_stimulus':
        // Source-Based Question: a passage / table / chart / map source, then
        // follow-up sub-questions. Same passage data model, passageKind
        // 'source'. The teacher attaches the source (text and/or image) and
        // adds the questions underneath.
        newSection = createPassageSection({
          passageKind: 'source',
          title: 'Study the source below and answer the questions that follow.',
          questions: [
            { type: 'short_answer', options: [], correctAnswer: '', marks: 1, answerFormat: 'lines', answerLines: 2 },
          ],
        })
        break
      case 'labelled_diagram':
        // Labelled Diagram Question: a diagram stimulus whose first sub-question
        // uses the "labelled blanks" answer format (P: ____, Q: ____, R: ____)
        // so the student names each labelled part.
        newSection = createPassageSection({
          passageKind: 'diagram',
          title: 'Study the diagram below and answer the questions that follow.',
          questions: [
            {
              type: 'short_answer',
              options: [],
              correctAnswer: '',
              marks: 3,
              text: 'Name the parts labelled P, Q and R.',
              answerFormat: 'labelled_blanks',
              blankLabels: ['P', 'Q', 'R'],
            },
          ],
        })
        break
      case 'image_identify':
        // Image Identify is a diagram-with-labels question rendered in
        // "identify" mode: numbered markers print on the image, and the
        // student writes the matching term on numbered blank lines below.
        // Reuses all the diagramLabels infrastructure (PR #430).
        newSection = baseQuestion('diagram', {
          options: [],
          correctAnswer: '',
          marks: 5,
          diagramText: 'Identify the labelled parts',
          diagramMode: 'identify',
        })
        break
      case 'pagebreak':
        newSection = createPagebreakSection()
        break
      case 'section': {
        addPart()
        showToast('Section added.')
        closeSlide()
        return
      }
      case 'ai_generate':
      case 'generate_diagram':
        // Both AI block-picker entries open the AI tools slide; the free-form
        // diagram generator (DiagramGeneratorAction) lives there alongside
        // question generation.
        openSlide('ai')
        return
      case 'question_bank':
        // Capture the insert position before closeSlide() clears it, then
        // open the bank picker. Insertion happens on pick.
        setBankPicker({ open: true, afterIndex: insertAfterIndex })
        closeSlide()
        return
      default:
        showToast('That block type is coming soon.', true)
        return
    }
    if (newSection) {
      insertSectionAfter(insertAfterIndex, newSection)
      showToast('Block added.')
    }
    closeSlide()
  }

  // Save the question currently being edited (inline card) into the teacher's
  // reusable bank. Paper-specific links are stripped in the service.
  async function handleSaveToBank(question) {
    if (!currentUser?.uid) { showToast('Sign in to save questions.', true); return }
    if (!richTextHasContent(question?.text)) {
      showToast('Add question text before saving to the bank.', true)
      return
    }
    try {
      await saveQuestionToBank(currentUser.uid, question, {
        subject: form.subject, grade: form.grade, topic: form.topic,
      })
      showToast('Saved to your question bank.')
    } catch (error) {
      showToast(`Could not save: ${getErrorMessage(error)}`, true)
    }
  }

