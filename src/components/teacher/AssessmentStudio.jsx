  useEffect(() => {
    if (!currentUser?.uid) return
    // The cross-device draft is for unsaved NEW papers only. When editing an
    // existing assessment, the durable copy in Firestore is the source of
    // truth — don't shadow it with (or restore from) the new-paper draft.
    if (isEditing) return
    if (!draftRestoredRef.current) return
    // Once the paper is filed in the library (below), the library autosave is
    // the source of truth — stop maintaining a parallel "new paper" draft that
    // could otherwise resurrect as a duplicate on the next visit to /new.
    if (createdIdRef.current) return
    if (hasOnlyEmptyStarterSection(sections) && !form.title.trim() && !form.schoolName.trim()) return
    const timer = setTimeout(() => {
      const payload = { form, sections, parts, view }
      saveAssessmentDraft(currentUser.uid, payload)
      // Mirror to Firestore so the draft follows the teacher across devices.
      // Fire-and-forget; failures fall back to the local copy.
      saveAssessmentDraftRemote(currentUser.uid, payload)
      setDraftSavedAt(Date.now())
      // The device draft autosave has captured the latest edits — clear the
      // "unsaved" flag. NOTE: this does NOT clear `libraryDirty`; the library
      // copy is only current after a real persistAssessment.
      setDirty(false)
    }, 800)
    return () => clearTimeout(timer)
  }, [form, sections, parts, view, currentUser?.uid, isEditing])

  // ── Continuous autosave to the durable library ──────────────────────────
  // Files the paper in the teacher's library — and keeps it updated as they
  // edit — without an explicit "Save to library" click, so their work is never
  // stranded as a draft-only copy (covers both Exam Studio and Test Paper
  // Studio). Heavier than the device draft autosave (it serializes, uploads
  // images and writes the assessment doc), so it runs on a longer debounce,
  // never overlaps itself, and yields to an explicit save / export / import /
  // generation via the gate in shouldAutosaveToLibrary. Best-effort: a failure
  // leaves the draft holding the work and retries on the next edit.
  useEffect(() => {
    const ok = shouldAutosaveToLibrary({
      uid: currentUser?.uid,
      questionCount,
      libraryDirty,
      saving,
      exporting,
      editLoading,
      importing: importingDocument,
      generating: aiGenerating,
    })
    if (!ok) return undefined
    const timer = setTimeout(() => {
      // persistAssessment is single-flight via persistInFlightRef, so a manual
      // save/export that fires mid-debounce won't double-create the doc.
      runLibraryPersist().catch((err) => {
        console.error('Library autosave failed', err)
      })
    }, 2000)
    return () => clearTimeout(timer)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [form, sections, parts, libraryDirty, questionCount, saving, exporting,
    editLoading, importingDocument, aiGenerating, currentUser?.uid])

  // ── Edit mode: load the existing assessment + its questions ──────────
  // Hydrates the same in-memory shape the builder already uses, so every
  // block type (incl. essay/numeric/matching/sequence and short-answer
  // passage sub-questions) reopens exactly as saved.
  useEffect(() => {
    if (!isEditing || !editId || !currentUser?.uid) return
    let cancelled = false
    setEditLoading(true)
    setEditError(null)
    Promise.all([getAssessmentById(editId), getAssessmentQuestions(editId)])
      .then(([assessment, questions]) => {
        if (cancelled) return
        if (!assessment) { setEditError('notfound'); setEditLoading(false); return }
        if (!isAdmin && assessment.createdBy !== currentUser.uid) {
          setEditError('denied'); setEditLoading(false); return
        }
        setForm(current => ({ ...current, ...mapAssessmentToForm(assessment) }))
        const hydrated = hydrateQuizSections(
          questions,
          assessment.passages || [],
          assessment.parts || [],
          assessment.pagebreaks || [],
        )
        setSections(hydrated.sections)
        setParts(hydrated.parts)
        setDeletedIds([])
        // The loaded paper is the new undo baseline — not the empty starter.
        resetUndoBaseline()
        setView('builder')
        // The loaded paper is already in the library and not yet edited.
        setSavedToLibrary(true)
        setDirty(false)
        setLibraryDirty(false)
        // Don't let the freshly-loaded setState flip the "unsaved" badge or
        // trigger a draft restore that clobbers it.
        draftRestoredRef.current = true
        dirtyTrackingReadyRef.current = false
        setEditLoading(false)
      })
      .catch(() => {
        if (!cancelled) { setEditError('notfound'); setEditLoading(false) }
      })
    return () => { cancelled = true }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [editId, isEditing, currentUser?.uid, isAdmin])

  // Mark the paper "dirty" the moment its content changes, so the status badge
  // can show "Unsaved changes" until the debounced autosave above clears it.
  // The first run (initial mount + async draft restore) is skipped so an
  // untouched paper never reads as unsaved; a real library save also clears it.
  const dirtyTrackingReadyRef = useRef(false)
  useEffect(() => {
    if (!dirtyTrackingReadyRef.current) { dirtyTrackingReadyRef.current = true; return }
    if (hasOnlyEmptyStarterSection(sections) && !form.title.trim() && !form.schoolName.trim()) return
    setDirty(true)
    setLibraryDirty(true)
    setSavedToLibrary(false)
  }, [form, sections, parts])

  useEffect(() => () => revokeImportedQuizAssets(importedAssets), [importedAssets])

  /* ------------ paper-level undo / redo ------------ */
  // TipTap handles undo *inside* each text field; this covers structural
  // edits — add/remove/reorder questions & parts, header fields, type
  // switches — over the whole paper's form + sections + parts.
  const undoableValue = useMemo(() => ({ form, sections, parts }), [form, sections, parts])
  // Latest snapshot, read by the baseline-reset effect below without making it
  // depend on (and re-run for) every keystroke.
  const undoableValueRef = useRef(undoableValue)
  undoableValueRef.current = undoableValue
  const applyUndoable = useCallback((snap) => {
    if (!snap) return
    setForm(snap.form)
    setSections(snap.sections)
    setParts(snap.parts)
  }, [])
  const { undo, redo, canUndo, canRedo, reset: resetUndo } = useUndoRedo(undoableValue, applyUndoable)

  // Wholesale paper replacements (edit-mode load, AI "create paper", document
  // import, cross-device draft restore) must re-seed the undo baseline to the
  // NEW content. Without this the hook's baseline stays the empty starter, so
  // the first Ctrl+Z on a loaded/imported/AI paper silently wipes it back to a
  // single blank question. Each replace site bumps this token; the effect then
  // reseeds from the post-update value.
  const [undoBaselineToken, setUndoBaselineToken] = useState(0)
  const resetUndoBaseline = useCallback(() => setUndoBaselineToken((n) => n + 1), [])
  useEffect(() => {
    if (undoBaselineToken === 0) return
    resetUndo(undoableValueRef.current)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [undoBaselineToken])

  // Guard against losing unsaved work to a tab close / reload / external
  // navigation. The autosave covers new papers across devices, but edit-mode
  // papers have no draft, so a stray reload would otherwise discard every
  // change with no warning.
  useEffect(() => {
    if (!dirty) return undefined
    const onBeforeUnload = (e) => { e.preventDefault(); e.returnValue = '' }
    window.addEventListener('beforeunload', onBeforeUnload)
    return () => window.removeEventListener('beforeunload', onBeforeUnload)
  }, [dirty])

  // Global keyboard shortcuts. We deliberately let the browser/TipTap handle
  // Ctrl+Z while focus is in a text field so typing-level undo keeps working;
  // only when focus is outside an editable element do we drive paper undo.
  useEffect(() => {
    function onKeyDown(e) {
      const key = e.key.toLowerCase()
      if (key !== 'z' && key !== 'y') return
      if (!(e.ctrlKey || e.metaKey)) return
      const el = e.target
      const tag = el?.tagName
      const editable = tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT' ||
        el?.isContentEditable
      if (editable) return
      const wantRedo = key === 'y' || (key === 'z' && e.shiftKey)
      e.preventDefault()
      if (wantRedo) redo()
      else undo()
    }
    window.addEventListener('keydown', onKeyDown)
    return () => window.removeEventListener('keydown', onKeyDown)
  }, [undo, redo])

