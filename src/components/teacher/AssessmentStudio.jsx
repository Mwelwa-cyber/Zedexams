  function moveSection(sectionIndex, direction) {
    setSections(prev => {
      const next = [...prev]
      const target = sectionIndex + direction
      if (target < 0 || target >= next.length) return next
      ;[next[sectionIndex], next[target]] = [next[target], next[sectionIndex]]
      return next
    })
  }
  function removeSectionAt(sectionIndex) {
    // Queue any already-saved question ids for deletion so the edit-save
    // batch removes them from Firestore (no-op for never-saved sections).
    const removedIds = collectSectionFirestoreIds(sections[sectionIndex])
    if (removedIds.length) setDeletedIds(prev => [...prev, ...removedIds])
    setSections(prev => {
      const next = prev.filter((_, index) => index !== sectionIndex)
      return next.length ? next : [createStandaloneSection()]
    })
  }
  function duplicateSectionAt(sectionIndex) {
    setSections(prev => {
      const source = prev[sectionIndex]
      if (!source) return prev
      const cloned = source.kind === 'passage'
        ? createPassageSection({
            ...source.passage,
            id: undefined,
            questions: (source.passage.questions || []).map(q => ({ ...q, _id: null })),
          })
        : buildStandaloneSection({ ...source.question, _id: null })
      const next = [...prev]
      next.splice(sectionIndex + 1, 0, cloned)
      return next
    })
  }

  // Clear the whole paper body back to a single blank block. Queues every
  // already-saved question id for deletion so an edit-mode save removes them
  // from Firestore (no-op for a never-saved paper). Header fields (title,
  // grade, school, etc.) are left intact — this clears questions, not the
  // paper's identity. Tracked by the undo stack, so a stray click is one
  // Ctrl+Z away.
  function clearAllBlocks() {
    const removedIds = sections.flatMap(collectSectionFirestoreIds)
    if (removedIds.length) setDeletedIds(prev => [...prev, ...removedIds])
    setSections([createStandaloneSection()])
    setParts([])
  }

  function insertSectionAfter(afterIndex, section) {
    setSections(prev => {
      if (hasOnlyEmptyStarterSection(prev)) return [section]
      if (afterIndex == null) return [...prev, section]
      const next = [...prev]
      next.splice(afterIndex + 1, 0, section)
      return next
    })
  }

  function addPart() {
    // Leave the title blank (the A/B/C letter is derived from position, so it
    // stays correct after a reorder; the title input is for an optional
    // descriptive name like "Multiple Choice"). Matches CreateQuizV2/EditQuizV2.
    setParts(prev => [
      ...prev,
      createPartGroup({ order: prev.length, title: '' }),
    ])
  }
  // Reorder a whole Section (Part) relative to the other sections AND the block
  // of loose / ungrouped questions. `direction` is -1 (up) or +1 (down).
  // Swapping a section past the ungrouped block is how a teacher puts a section
  // header "on top" of questions that aren't in any section yet. We rewrite both
  // the parts[] order (which drives the A/B/C letter) and `ungroupedOrder`
  // (where the loose-questions block sits) so the builder, preview, PDF and DOCX
  // all stay in step.
  function moveSectionGroup(partId, direction) {
    const hasUngrouped = sections.some(section => {
      const pid = section.kind === 'passage'
        ? section.partId ?? null
        : section.question?.partId ?? null
      return !pid
    })
    const groups = orderPaperGroups(parts, form.ungroupedOrder ?? 0, hasUngrouped)
    const fromIndex = groups.findIndex(group => group.type === 'part' && group.part.id === partId)
    const toIndex = fromIndex + direction
    if (fromIndex < 0 || toIndex < 0 || toIndex >= groups.length) return
    const reordered = [...groups]
    ;[reordered[fromIndex], reordered[toIndex]] = [reordered[toIndex], reordered[fromIndex]]
    const ungroupedIndex = reordered.findIndex(group => group.type === 'ungrouped')
    const partsBeforeUngrouped = ungroupedIndex < 0
      ? 0
      : reordered.slice(0, ungroupedIndex).filter(group => group.type === 'part').length
    setParts(reordered
      .filter(group => group.type === 'part')
      .map((group, index) => ({ ...group.part, order: index })))
    setF('ungroupedOrder', partsBeforeUngrouped)
  }
  function updatePart(partId, field, value) {
    setParts(prev => prev.map(part => part.id === partId ? { ...part, [field]: value } : part))
  }
  function removePart(partId) {
    setParts(prev => prev.filter(part => part.id !== partId).map((part, i) => ({ ...part, order: i })))
    setSections(prev => prev.map(section => {
      if (section.kind === 'passage' && section.partId === partId) {
        return {
          ...section,
          partId: null,
          passage: {
            ...section.passage,
            questions: (section.passage.questions || []).map(q =>
              q.partId === partId ? { ...q, partId: null } : q,
            ),
          },
        }
      }
      if (section.kind === 'standalone' && section.question?.partId === partId) {
        return { ...section, question: { ...section.question, partId: null } }
      }
      return section
    }))
  }
  function assignSectionToPart(sectionId, partId) {
    setSections(prev => prev.map(section => {
      if (section.id !== sectionId) return section
      if (section.kind === 'passage') {
        return {
          ...section,
          partId: partId || null,
          passage: {
            ...section.passage,
            questions: (section.passage.questions || []).map(q => ({ ...q, partId: partId || null })),
          },
        }
      }
      return { ...section, question: { ...section.question, partId: partId || null } }
    }))
  }

