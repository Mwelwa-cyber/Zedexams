  // imageUrl of a fresh "structured" question whose text is the prompt
  // itself, so teachers can immediately edit the question wording.
  async function handleGenerateDiagram(prompt, provider = 'recraft') {
    const clean = String(prompt || '').trim()
    if (!clean) {
      showToast('Describe the diagram you want to generate.', true)
      return
    }
    setGeneratingDiagram(true)
    try {
      const { url } = await generateDiagram({ prompt: clean, provider })
      const newSection = buildStandaloneSection({
        type: 'diagram',
        detectedType: 'diagram',
        text: clean,
        imageUrl: url,
        // The generation prompt is a ready description of the figure — seed
        // the alt text with it so the image isn't shipped without one.
        imageAlt: clean.slice(0, 300),
        marks: 5,
        options: [],
        correctAnswer: '',
        wordBank: [],
      })
      setSections(prev => hasOnlyEmptyStarterSection(prev)
        ? [newSection]
        : [...prev, newSection])
      showToast('Diagram generated. Edit the question text or word bank to label it.')
      closeSlide()
      if (view !== 'builder') changeView('builder')
    } catch (error) {
      const raw = error?.message || ''
      const isUpgradeStyleKeyIssue = (provider === 'openai' || provider === 'kie')
        && /openai|photoreal|colour illustration|kie|OPENAI_API_KEY|KIE_API_KEY/i.test(raw)
        && /(invalid|not configured|not available|unavailable|rotate)/i.test(raw)
      const message = isUpgradeStyleKeyIssue
        ? `${provider === 'kie' ? 'Colour' : 'Photoreal'} is currently unavailable. Switch to Line art and try again.`
        : (raw || 'Diagram generation failed.')
      showToast(message, true)
    } finally {
      setGeneratingDiagram(false)
    }
  }

