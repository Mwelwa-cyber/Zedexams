  /* ------------ Create paper with AI ------------ */
  // Receives { blocks, assessment, form: aiPaperForm, mode } from
  // CreatePaperModal: blocks are studio-ready sections/parts from
  // aiPaperToSections. 'replace' swaps the whole paper; 'append' adds
  // after the existing questions (the empty starter section is dropped).
  function handleApplyAiPaper({ blocks, assessment, form: aiPaperForm, mode }) {
    const partOffset = mode === 'append' ? parts.length : 0
    const newParts = blocks.parts.map((p, i) => ({ ...p, order: partOffset + i }))
    // Compute the committed sections array explicitly so the auto-diagram pass
    // can attach images by the same indices that land in state.
    const baseSections = mode === 'replace'
      ? (blocks.sections.length ? blocks.sections : [createStandaloneSection()])
      : (hasOnlyEmptyStarterSection(sections) ? blocks.sections : [...sections, ...blocks.sections])
    setSections(baseSections)
    if (mode === 'replace') {
      setParts(newParts)
    } else {
      setParts(prev => [...prev, ...newParts])
    }
    // Fill paper metadata the teacher hasn't set yet — including their school
    // name from the saved School Profile (falling back to the most recent
    // saved paper), so AI-created papers print with the school header without
    // re-typing it each time.
    // The modal's assessmentType picker shares the SAME canonical registry as
    // the builder's own dropdown (paperTaxonomy.js ASSESSMENT_TYPES), so the
    // value it emits is applied straight through — no translation table.
    // The modal now emits a canonical subject KEY ('numeracy',
    // 'integrated_science'); the studio form carries a display label, so map
    // it back to something human-readable for the header/exports. The grade
    // goes with it — the combined maths/science area prints as
    // "Pre-Mathematics and Science" at Nursery/Reception and "Mathematics and
    // Science" from Grade 1, and never as its `numeracy` slug.
    const aiSubjectLabel = aiPaperForm.subject
      ? kbSubjectLabel(aiPaperForm.subject, aiPaperForm.grade) : ''
    // Builder + modal now share one level value scheme (bare number for primary
    // grades, 'G8'…'G12' for the forms). Carry the modal's chosen value through
    // verbatim so a Form paper stays a Form and is never relabelled a Grade.
    const aiStudioGrade = String(aiPaperForm.grade || '')
    setForm(f => {
      const lastWithSchool = recentPapers.find(p => (p.schoolName || '').trim())
      const recentBranding = {
        schoolName: lastWithSchool?.schoolName || '',
      }
      const branding = brandingForAiPaper(f, schoolProfile, recentBranding)
      return {
        ...f,
        // Grade/subject were chosen explicitly in the modal — the paper
        // follows them (unlike the fields below, which only backfill).
        grade: aiStudioGrade || f.grade,
        subject: aiSubjectLabel || f.subject,
        framework: normalizeStudioFramework(aiPaperForm.framework || f.framework),
        // The term was chosen explicitly in the modal, so the paper follows it —
        // like grade/subject/type above, and UNLIKE the backfill-only fields
        // below. It used to read `f.term || aiPaperForm.term`, and the form's
        // term always has a value ('1' from makeDefaultForm), so the teacher's
        // choice was silently discarded: pick Term 2, get a Term 1 paper, with
        // "TERM 1" printed in its title. That is Bug 2's misreported term.
        term: String(aiPaperForm.term || f.term || ''),
        duration: f.duration || String(aiPaperForm.durationMinutes),
        assessmentType: aiPaperForm.assessmentType || f.assessmentType,
        // Carry the generated paper's blueprint onto the studio form so the
        // analysis tools can verify against it and the save persists it.
        blueprint: aiPaperForm.blueprint || f.blueprint || null,
        coverInstructions: f.coverInstructions ||
          String(assessment?.header?.instructions || ''),
        // brandingForAiPaper already implements per-field form-wins, so all
        // its outputs apply — not just the school name.
        schoolName: branding.schoolName,
        schoolLogoUrl: branding.schoolLogoUrl,
        motto: branding.motto,
        address: branding.address,
        emisNumber: branding.emisNumber,
        footerText: branding.footerText,
      }
    })
    setCreatePaperOpen(false)
    closeSlide()
    changeView('builder')
    // The applied AI paper is the new undo baseline — not the empty starter.
    resetUndoBaseline()
    const flagged = blocks.warnings.length
    showToast(
      `AI paper ${mode === 'replace' ? 'created' : 'added'} — ` +
      `${blocks.questionCount} questions, ${blocks.totalMarks} marks.` +
      (flagged ? ` ${flagged} flagged for review.` : ' Review before saving.'),
    )
    // Close the diagram loop immediately. With "Draw diagrams automatically"
    // on (the default), generate every figure now; otherwise open the fixup
    // panel so the teacher attaches/generates them in one click rather than
    // discovering gaps at print time.
    if (countDiagramJobs(baseSections) > 0) {
      if (aiPaperForm?.autoDiagrams !== false) {
        runAutoDiagrams(baseSections)
      } else {
        setDiagramFixOpen(true)
      }
    }
  }

  // Attach a picture-bank / AI-generated figure to a diagram-flagged
  // question and clear its "Diagram needed" review note (un-flagging the
  // question entirely when that was the only note). `silent` suppresses the
  // per-attach toast during the automatic batch pass.
  function attachDiagramToSection(sectionIndex, url, { silent = false } = {}) {
    if (!url) return
    updateSection(sectionIndex, section => {
      const remainingNotes = (section.question.reviewNotes || [])
        .filter(n => !String(n).startsWith('Diagram needed:'))
      return {
        ...section,
        question: {
          ...section.question,
          imageUrl: url,
          imageAssetId: '',
          reviewNotes: remainingNotes,
          requiresReview: remainingNotes.length > 0,
        },
      }
    })
    if (!silent) showToast('Diagram attached.')
  }

  // Attach a generated figure to one option of a picture-based MCQ. Clears
  // the slot's pending brief and, once every option has its image, drops the
  // "Picture options needed" review note.
  function attachOptionDiagramToSection(sectionIndex, optionIndex, url) {
    if (!url) return
    updateSection(sectionIndex, section => {
      const existing = Array.isArray(section.question.optionMedia) ? section.question.optionMedia : []
      const next = existing.map(slot => (slot ? { ...slot } : slot))
      const slot = next[optionIndex] || { alt: '' }
      next[optionIndex] = { ...slot, imageUrl: url, alt: slot.alt || '', diagramBrief: '' }
      const stillNeeds = next.some(s => s && s.diagramBrief && !s.imageUrl)
      const remainingNotes = (section.question.reviewNotes || [])
        .filter(n => !String(n).startsWith('Picture options needed'))
      return {
        ...section,
        question: {
          ...section.question,
          optionMedia: next,
          reviewNotes: stillNeeds ? section.question.reviewNotes : remainingNotes,
          requiresReview: stillNeeds ? section.question.requiresReview : remainingNotes.length > 0,
        },
      }
    })
  }

  // Generate every pending figure on a freshly created AI paper, in the
  // background, with a progress banner. Reused implementation lives in
  // utils/autoGenerateDiagrams. Whatever's left (cap/error) opens the panel.
  async function runAutoDiagrams(snapshot) {
    const total = Math.min(countDiagramJobs(snapshot), DIAGRAM_AUTO_CAP)
    if (total === 0) return
    setAutoDiagram({ running: true, done: 0, total })
    const result = await autoGenerateDiagrams(snapshot, {
      // Style selector, not a backend: 'recraft' = B&W line art rendered on
      // gpt-image-1 (the Recraft service itself was decommissioned).
      provider: 'recraft',
      cap: DIAGRAM_AUTO_CAP,
      attachStem: (i, url) => attachDiagramToSection(i, url, { silent: true }),
      attachOption: (i, oi, url) => attachOptionDiagramToSection(i, oi, url),
      onProgress: ({ done, total: t }) => setAutoDiagram({ running: true, done, total: t }),
    })
    setAutoDiagram({ running: false, done: result.done, total: result.total })
    if (result.error) {
      showToast(`Drew ${result.done}/${result.total} diagrams — ${result.error}`, true)
    } else if (result.done > 0) {
      showToast(`Added ${result.done} diagram${result.done === 1 ? '' : 's'} to the paper.`)
    }
    if (result.remaining > 0) setDiagramFixOpen(true)
    window.setTimeout(() => setAutoDiagram(null), 4000)
  }


  /* ------------ AI generation ------------ */
  async function handleGenerateQuestions(topicOverride) {
    // Multi-topic: the picker collects an array of topics + sub-topics. Join
    // them for the generator (which grounds on the joined string + spreads the
    // questions across every listed topic), mirroring the full-paper modal.
    const topicsList = Array.isArray(aiForm.topics) ? aiForm.topics.filter(Boolean) : []
    const subtopicsList = Array.isArray(aiForm.subtopics) ? aiForm.subtopics.filter(Boolean) : []
    const topic = (topicOverride
      ? String(topicOverride)
      : (topicsList.join('; ') || aiForm.topic || form.topic || '')).trim().slice(0, 240)
    if (!topic) {
      showToast('Add at least one topic so Zed can generate questions.', true)
      return
    }
    // A readable title falls back to the first topic rather than the whole
    // '; '-joined list, which would run long across several topics.
    const titleTopic = topicsList[0] || topic
    await runGenerateQuestions(async () => {
      try {
        const { questions: generated, warning: kbWarning } = await generateAIQuizQuestions({
          subject: form.subject,
          grade: form.grade,
          topic,
          subtopic: subtopicsList.join('; ').slice(0, 300),
          count: aiForm.count,
          type: aiForm.type,
          framework: normalizeStudioFramework(form.framework),
        })
        const { usable, dropped } = partitionUsableQuestions(generated)
        if (!usable.length) {
          showToast('Zed could not generate questions. Try again.', true)
          return
        }
        // Nothing touches the paper yet — the batch lands in the review panel
        // (AiReviewPanel inside AiSlide) for an accept/discard pass, with the
        // dropped-as-incomplete count reported instead of silently swallowed.
        setAiReview({
          questions: usable,
          droppedCount: dropped.length,
          titleTopic,
          kbWarning: kbWarning || '',
        })
      } catch (error) {
        // Map daily-cap / timeout / offline to calm copy instead of a raw
        // callable string ("resource-exhausted", "internal", …).
        showToast(friendlyMessage(error, 'AI generation failed. Please try again.'), true)
      }
    })
  }

  // "Add N questions" from the review panel — the only path that inserts the
  // quick-generated questions into the paper.
  function handleConfirmAiReview(acceptedQuestions) {
    if (!aiReview) return
    const list = Array.isArray(acceptedQuestions) ? acceptedQuestions : []
    if (!list.length) { setAiReview(null); return }
    const nextSections = list.map(q => buildStandaloneSection({
      ...q,
      options: q.options?.length ? q.options : ['', '', '', ''],
    }))
    setSections(prev => hasOnlyEmptyStarterSection(prev)
      ? nextSections
      : [...prev, ...nextSections])
    if (!form.title.trim()) setF('title', `${paperGradeLabel(form.grade)} ${form.subject} - ${aiReview.titleTopic}`)
    const dropped = aiReview.droppedCount
    showToast(dropped
      ? `Added ${nextSections.length} question${nextSections.length === 1 ? '' : 's'} — ${dropped} incomplete ${dropped === 1 ? 'was' : 'were'} dropped.`
      : `Added ${nextSections.length} AI-generated question${nextSections.length === 1 ? '' : 's'}. Review before saving.`)
    if (aiReview.kbWarning) {
      const warning = aiReview.kbWarning
      setTimeout(() => showToast(warning), 1500)
    }
    setAiReview(null)
    closeSlide()
    if (view !== 'builder') changeView('builder')
  }

  /* ------------ AI diagram generation ------------ */
  // The generated PNG lives in Firebase Storage; we attach it as the
  // imageUrl of a fresh "structured" question whose text is the prompt
  // itself, so teachers can immediately edit the question wording.
  // `style` is one of the legacy wire values 'recraft' | 'openai' | 'kie' —
  // pure style selectors (line art / photoreal / colour illustration); every
  // one of them renders on gpt-image-1 since Recraft and Kie were
  // decommissioned.
  async function handleGenerateDiagram(prompt, style = 'recraft') {
    const clean = String(prompt || '').trim()
    if (!clean) {
      showToast('Describe the diagram you want to generate.', true)
      return
    }
    setGeneratingDiagram(true)
    try {
      const { url } = await generateDiagram({ prompt: clean, provider: style })
      const newSection = buildStandaloneSection({
        type: 'diagram',
        detectedType: 'diagram',
        text: clean,
        imageUrl: url,
        // The generation prompt is a ready description of the figure — seed
        // the alt text with it so the image isn't shipped without one.
        imageAlt: clean.slice(0, 300),
        marks: 5,
        options: [],
        correctAnswer: '',
        wordBank: [],
      })
      setSections(prev => hasOnlyEmptyStarterSection(prev)
        ? [newSection]
        : [...prev, newSection])
      showToast('Diagram generated. Edit the question text or word bank to label it.')
      closeSlide()
      if (view !== 'builder') changeView('builder')
    } catch (error) {
      const raw = error?.message || ''
      // Every style renders on gpt-image-1, so a key/config failure means
      // image generation is down for ALL styles — never advise switching
      // styles (the old copy said "Switch to Line art", which fails the
      // same way and just wastes the teacher's time).
      const isKeyConfigIssue =
        /OPENAI_API_KEY|KIE_API_KEY|openai|photoreal|colour illustration|kie/i.test(raw)
        && /(invalid|not configured|not available|unavailable|rotate)/i.test(raw)
      const message = isKeyConfigIssue
        ? 'Image generation is temporarily unavailable — please try again shortly.'
        : (raw || 'Diagram generation failed.')
      showToast(message, true)
    } finally {
      setGeneratingDiagram(false)
    }
  }

