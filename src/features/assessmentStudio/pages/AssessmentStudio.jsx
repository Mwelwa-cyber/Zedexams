// Reverse of the createAssessment payload: map a stored assessment doc back
// onto the studio's `form` shape so editing reopens with every paper-level
// field (cover toggles, MCQ layout, import metadata) intact.
// Only defined keys are returned so the caller can spread over form defaults.
function mapAssessmentToForm(a = {}) {
  const out = {}
  const copy = (key, transform) => {
    if (a[key] !== undefined && a[key] !== null) out[key] = transform ? transform(a[key]) : a[key]
  }
  // A title THIS CODEBASE generated is deliberately NOT carried into the form.
  // `form.title` means "the teacher named this paper themselves", and the studio
  // regenerates the name from the paper's own fields whenever it is blank — so
  // leaving a generated title out is what lets a paper saved under the old
  // subject-less name pick up its subject and real term the next time it is
  // saved. A name a human chose is copied through untouched.
  if (typeof a.title === 'string' && a.title.trim()
    && !isGeneratedAssessmentTitle(a.title, a)) {
    out.title = a.title
  }
  if (a.subject != null) out.subject = normalizeSubject(a.subject)
  // Normalise a saved grade into the picker's value scheme ('Grade 4' → '4',
  // 'Nursery' → 'ECE_N', 'Form 1' → 'G8'). A legacy secondary "Grade 8"…"12"
  // is deliberately kept as its bare number (NOT converted to a Form) so old
  // papers open under their original level, flagged Legacy in the picker.
  copy('grade', (g) => paperLevel(g)?.value ?? String(g))
  copy('term', String)
  // The blueprint the paper was generated against, so reopening it keeps the
  // planned-vs-actual view rather than falling back to discovery.
  copy('blueprint')
  copy('year')
  copy('duration')
  copy('topic')
  copy('assessmentType')
  copy('framework', normalizeStudioFramework)
  copy('schoolName')
  // School identity from Teacher Settings → My School (printed in the paper
  // header alongside the school name).
  copy('schoolLogoUrl')
  copy('motto')
  copy('address')
  copy('emisNumber')
  copy('footerText')
  copy('className')
  copy('paperName')
  copy('assessmentDate')
  copy('coverInstructions')
  copy('endOfPaperText')
  copy('mcqOptionLayout')
  // Read the new field first and fall back to the legacy one, so a paper saved
  // by either build opens with the count its author chose (§3).
  if (a.answerChoiceCount != null) out.mcqAnswerChoiceCount = a.answerChoiceCount
  else copy('mcqAnswerChoiceCount')
  copy('gradeNumberStyle')
  copy('nameFieldStyle')
  copy('nameFieldLabel')
  // §2 — the sheet, read from the layout object with the loose top-level fields
  // as a fallback for papers saved before the object existed.
  if (a.layout && typeof a.layout === 'object') {
    if (a.layout.pageSize) out.pageSize = a.layout.pageSize
    if (a.layout.orientation) out.orientation = a.layout.orientation
    if (a.layout.margins) out.margins = a.layout.margins
  } else {
    copy('pageSize')
    copy('orientation')
    copy('margins')
  }
  copy('ungroupedOrder')
  copy('mode')
  copy('importStatus')
  copy('sourceFileName')
  copy('sourceContentType')
  if (Array.isArray(a.importWarnings)) out.importWarnings = a.importWarnings
  for (const key of [
    'showNameField', 'showDateField', 'showMarksField', 'showClassField',
    'showQuestionMarks', 'allowPerQuestionChoiceCount',
  ]) {
    if (typeof a[key] === 'boolean') out[key] = a[key]
  }
  return out
}

// The name the paper is FILED under — the library, Recent Documents, the
// dashboard and the download filename all show this. It carries the subject and
// the term (read from the paper, never defaulted), because identifying one paper
// among a teacher's others is its whole job: without them, every Grade 4
// end-of-term paper a teacher wrote in 2026 was called the same thing.
