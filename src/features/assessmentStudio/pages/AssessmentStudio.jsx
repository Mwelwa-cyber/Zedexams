function buildFooterCode(form) {
  const parts = [
    studioGradeToKbGrade(form.grade) || '',
    form.subject || '',
    `Term ${form.term || ''}`,
    String(form.year || new Date().getFullYear()),
  ].filter(Boolean)
  return parts.join('/')
}


