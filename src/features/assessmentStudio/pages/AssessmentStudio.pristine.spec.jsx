import AssessmentStudio from './AssessmentStudio'

// Long enough to clear the 800ms device-draft debounce AND the 2s library
// autosave debounce, with room to spare.
const PAST_EVERY_AUTOSAVE_MS = 6000

function everyPersistenceCall() {
  return {
    papersCreated: mockCreateAssessment.mock.calls.length,
    questionsWritten: mockSaveAssessmentQuestions.mock.calls.length,
    papersUpdated: mockUpdateAssessmentWithQuestions.mock.calls.length,
    draftsSaved: mockSaveDraft.mock.calls.length,
    remoteDraftsSaved: mockSaveDraftRemote.mock.calls.length,
  }
}

// Let the mounted studio's async effects (school profile read, draft read)
// settle, then run every debounce out.
async function settleAndRunTimers(ms = PAST_EVERY_AUTOSAVE_MS) {
  await act(async () => { await Promise.resolve() })
  await act(async () => { vi.advanceTimersByTime(ms) })
  await act(async () => { await Promise.resolve() })
}

beforeEach(() => {
  vi.clearAllMocks()
  vi.useFakeTimers({ shouldAdvanceTime: true })
})

afterEach(() => {
  vi.useRealTimers()
})

describe('AssessmentStudio — an untouched new paper persists nothing', () => {
  it('THE BUG: mounting /new and doing nothing writes no paper, no question, no draft', async () => {
    render(<MemoryRouter><AssessmentStudio /></MemoryRouter>)
    await settleAndRunTimers()

    // The School Profile HAS been applied — otherwise this spec is testing a
    // studio the bug never affected.
    expect(screen.getByTestId('home-view')).toBeInTheDocument()
    expect(everyPersistenceCall()).toEqual({
      papersCreated: 0,
      questionsWritten: 0,
      papersUpdated: 0,
      draftsSaved: 0,
      remoteDraftsSaved: 0,
    })
  })

  it('clicking "New paper" and doing nothing also writes nothing', async () => {
    render(<MemoryRouter><AssessmentStudio /></MemoryRouter>)
    await settleAndRunTimers(0)

    fireEvent.click(screen.getByRole('button', { name: 'stub-new-paper' }))
    await settleAndRunTimers()

    expect(screen.getByTestId('builder-view')).toBeInTheDocument()
    expect(everyPersistenceCall()).toEqual({
      papersCreated: 0,
      questionsWritten: 0,
      papersUpdated: 0,
      draftsSaved: 0,
      remoteDraftsSaved: 0,
    })
  })

  it('typing into a header field drafts the paper but still does not file an empty one', async () => {
    render(<MemoryRouter><AssessmentStudio /></MemoryRouter>)
    await settleAndRunTimers(0)
    fireEvent.click(screen.getByRole('button', { name: 'stub-new-paper' }))
    await settleAndRunTimers(0)

    fireEvent.click(screen.getByRole('button', { name: 'stub-type-class' }))
    await settleAndRunTimers()

    // The edit is real, so the device draft captures it…
    expect(mockSaveDraft).toHaveBeenCalled()
    // …but a paper whose only question is blank is still not worth filing.
    expect(mockCreateAssessment).not.toHaveBeenCalled()
  })

  it('writing a question DOES file the paper — the autosave still works', async () => {
    render(<MemoryRouter><AssessmentStudio /></MemoryRouter>)
    await settleAndRunTimers(0)
    fireEvent.click(screen.getByRole('button', { name: 'stub-new-paper' }))
    await settleAndRunTimers(0)

    fireEvent.click(screen.getByRole('button', { name: 'stub-write-question' }))
    await settleAndRunTimers()

    expect(mockCreateAssessment).toHaveBeenCalledTimes(1)
    const [payload] = mockCreateAssessment.mock.calls[0]
    expect(payload.questionCount).toBe(1)
    // And the branding the studio seeded rides along on the real paper.
    expect(payload.schoolName).toBe('Kabulonga Primary School')
  })
})

describe('AssessmentStudio — the filed paper is named for its subject and term', () => {
  it('the generated title carries grade, subject, type, term and year', async () => {
    render(<MemoryRouter><AssessmentStudio /></MemoryRouter>)
    await settleAndRunTimers(0)
    fireEvent.click(screen.getByRole('button', { name: 'stub-new-paper' }))
    await settleAndRunTimers(0)
    fireEvent.click(screen.getByRole('button', { name: 'stub-write-question' }))
    await settleAndRunTimers()

    const [payload] = mockCreateAssessment.mock.calls[0]
    const year = new Date().getFullYear()
    // Defaults for a blank paper: Grade 4, Integrated Science, end-of-term, term 1.
    expect(payload.title).toBe(`GRADE 4 INTEGRATED SCIENCE - END OF TERM 1 TEST - ${year}`)
    expect(payload.titleSource).toBe('auto')
  })
})
