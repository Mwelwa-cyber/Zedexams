/**
 * Regression spec: LOADING the Assessment Paper Studio must persist NOTHING.
 *
 * The bug: visiting /teacher/assessment-papers/new and doing nothing — no
 * typing, no clicks — filed a paper holding one blank question into the
 * teacher's library about two seconds later, plus a device/cloud draft. It
 * reproduced every time, and it polluted the library and the dashboard's Recent
 * Documents feed with junk.
 *
 * Root cause: the studio decided "the teacher has edited this paper" from paper
 * CONTENT — "one empty starter question AND no title AND no school name" — and
 * its OWN School-Profile seeding writes the teacher's school name onto an
 * untouched paper. Every teacher with a saved school name therefore had an
 * apparently-edited paper the moment the page finished loading. The autosave
 * gate then counted the blank starter question as content and filed it.
 *
 * So the school profile in this spec is not incidental colour: it is the
 * trigger. Without it the old code passes and this spec proves nothing.
 *
 * Covered here:
 *   • mount /new, run past both autosave debounces → zero writes of any kind;
 *   • the same after clicking "New paper" (startBlankPaper is a second route in);
 *   • the first real edit DOES persist — otherwise "no writes" would be
 *     satisfied by an autosave that never works at all.
 */
