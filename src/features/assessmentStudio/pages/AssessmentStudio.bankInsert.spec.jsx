import AssessmentStudio from './AssessmentStudio'

function questions() {
  return JSON.parse(screen.getByTestId('builder-view').getAttribute('data-questions'))
}
function builder() {
  return screen.getByTestId('builder-view')
}

async function openBank() {
  fireEvent.click(await screen.findByText('stub-add-block'))
  fireEvent.click(await screen.findByText('stub-pick-bank'))
}

/** Use → pick a labelled position → confirm. */
async function insertAt(useButton, positionLabel, { andEdit = false } = {}) {
  fireEvent.click(await screen.findByText(useButton))
  await screen.findByRole('dialog', { name: /Choose where this question goes/i })
  if (positionLabel) fireEvent.click(screen.getByRole('button', { name: positionLabel }))
  fireEvent.click(screen.getByRole('button', {
    name: andEdit ? /Insert and edit/ : /^Insert as Q\d+$/,
  }))
}

describe('AssessmentStudio — inserting from the Question Bank', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    searchParams = new URLSearchParams('view=builder')
    render(<MemoryRouter><AssessmentStudio /></MemoryRouter>)
  })

  it('Use opens the placement step and inserts nothing on its own', async () => {
    await openBank()
    expect(questions()).toHaveLength(1)
    expect(questions()[0].text).toBe('')

    fireEvent.click(await screen.findByText('stub-use-mcq'))
    expect(await screen.findByRole('dialog', { name: /Choose where this question goes/i })).toBeInTheDocument()

    // Still the blank starter — nothing has been placed.
    expect(questions()).toHaveLength(1)
    expect(questions()[0].text).toBe('')
    expect(bumpQuestionUsage).not.toHaveBeenCalled()
  })

  it('cancelling the placement step leaves the paper untouched', async () => {
    await openBank()
    fireEvent.click(await screen.findByText('stub-use-mcq'))
    await screen.findByRole('dialog', { name: /Choose where this question goes/i })
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))

    await waitFor(() => expect(
      screen.queryByRole('dialog', { name: /Choose where this question goes/i }),
    ).not.toBeInTheDocument())
    expect(questions()).toHaveLength(1)
    expect(bumpQuestionUsage).not.toHaveBeenCalled()
  })

  it('the first insert replaces the blank starter and carries its provenance', async () => {
    await openBank()
    await insertAt('stub-use-mcq')

    await waitFor(() => expect(questions()).toHaveLength(1))
    const [q] = questions()
    expect(q.text).toBe('Add 1/2 and 1/4')
    expect(q.optionCount).toBe(4)
    expect(q.sourceQuestionId).toBe('row-mcq')
    expect(q.sourceBank).toBe('mine')
    expect(q.sourceVersion).toBe(3)
    expect(q.sourceBankId).toBe('row-mcq')
    expect(q.hasInsertedAt).toBe(true)
    // A copy is new work in THIS paper: never pre-locked, never pre-edited,
    // whatever the bank record happened to carry.
    expect(q.locked).toBe(false)
    expect(q.teacherEdited).toBe(false)
  })

  it('inserting at a chosen position shifts the questions after it down', async () => {
    await openBank()
    await insertAt('stub-use-mcq')
    await waitFor(() => expect(questions()).toHaveLength(1))

    // Placed AT Q1, not appended — so the question already there becomes Q2.
    // Two different questions, because "the paper grew" is not the claim;
    // "it grew in the right place" is, and identical rows cannot show that.
    await insertAt('stub-use-mcq-2', 'as Q1')
    await waitFor(() => expect(questions()).toHaveLength(2))
    expect(questions().map(q => q.text)).toEqual(['Which is larger?', 'Add 1/2 and 1/4'])

    // …and the end-of-section position lands after both, not at the front.
    await insertAt('stub-use-mcq', 'as Q3 (end of section)')
    await waitFor(() => expect(questions()).toHaveLength(3))
    expect(questions().map(q => q.text))
      .toEqual(['Which is larger?', 'Add 1/2 and 1/4', 'Add 1/2 and 1/4'])
  })

  it('a middle position lands in the middle, between the two named questions', async () => {
    await openBank()
    await insertAt('stub-use-mcq')
    await waitFor(() => expect(questions()).toHaveLength(1))
    await insertAt('stub-use-mcq-2', 'as Q2 (end of section)')
    await waitFor(() => expect(questions()).toHaveLength(2))
    expect(questions().map(q => q.text)).toEqual(['Add 1/2 and 1/4', 'Which is larger?'])

    // Q2 of three: the existing Q2 becomes Q3 and Q1 does not move.
    await insertAt('stub-use-mcq', 'as Q2')
    await waitFor(() => expect(questions()).toHaveLength(3))
    expect(questions().map(q => q.text))
      .toEqual(['Add 1/2 and 1/4', 'Add 1/2 and 1/4', 'Which is larger?'])
  })

  it('the usage counter is bumped once per insert — twice for two rapid inserts', async () => {
    await openBank()
    await insertAt('stub-use-mcq')
    await waitFor(() => expect(questions()).toHaveLength(1))
    await insertAt('stub-use-mcq', 'as Q1')
    await waitFor(() => expect(questions()).toHaveLength(2))

    expect(bumpQuestionUsage).toHaveBeenCalledTimes(2)
    expect(bumpQuestionUsage).toHaveBeenNthCalledWith(1, 'row-mcq')
    expect(bumpQuestionUsage).toHaveBeenNthCalledWith(2, 'row-mcq')
  })

  it('"Insert and edit" inserts and opens the editor on the new copy', async () => {
    await openBank()
    await insertAt('stub-use-mcq', null, { andEdit: true })
    await waitFor(() => expect(questions()).toHaveLength(1))
    expect(await screen.findByTestId('editor-slide')).toBeInTheDocument()
  })

  it('the drawer stays open, so several questions can be inserted in a row', async () => {
    await openBank()
    await insertAt('stub-use-mcq')
    await waitFor(() => expect(questions()).toHaveLength(1))
    expect(screen.getByText('stub-use-mcq')).toBeInTheDocument()
  })

  it('a question with nowhere to go gets a section added and is inserted into it', async () => {
    await openBank()
    await insertAt('stub-use-mcq')
    await waitFor(() => expect(questions()).toHaveLength(1))
    expect(builder().getAttribute('data-part-count')).toBe('0')

    // A True/False question cannot join an all-MCQ paper, and is never
    // converted so that it can.
    fireEvent.click(await screen.findByText('stub-use-tf'))
    await screen.findByRole('dialog', { name: /Choose where this question goes/i })
    expect(screen.getByText(/nowhere to put a true \/ false question/i)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /Add a True \/ False section/i }))

    await waitFor(() => expect(questions()).toHaveLength(2))
    expect(builder().getAttribute('data-part-count')).toBe('1')
    expect(builder().getAttribute('data-part-titles')).toBe('True / False')

    const inserted = questions()[1]
    expect(inserted.type).toBe('tf')
    expect(inserted.partId).toBeTruthy()
    // Provenance says master, because the row belongs to another teacher.
    expect(inserted.sourceBank).toBe('master')
    // No stored version on that row → null, never NaN (Firestore rejects it).
    expect(inserted.sourceVersion).toBeNull()
  })

  it('nothing in the insert flow writes to the bank', async () => {
    await openBank()
    await insertAt('stub-use-mcq')
    await waitFor(() => expect(questions()).toHaveLength(1))
    await insertAt('stub-use-mcq', 'as Q1')
    await waitFor(() => expect(questions()).toHaveLength(2))

    // Use creates ZERO bank documents and edits none: the usage counter is the
    // only thing an insert may touch.
    expect(saveQuestionToBank).not.toHaveBeenCalled()
    expect(duplicateBankQuestion).not.toHaveBeenCalled()
    expect(editMyBankQuestion).not.toHaveBeenCalled()
  })
})
