/**
 * The Question Bank insert, end to end inside the studio.
 *
 * The pieces are covered elsewhere — placement rules by
 * `test:question-bank-placement`, the picker's wording by
 * QuestionBankPlacementPicker.spec.jsx, the bank UI by
 * QuestionBankBrowser.spec.jsx, the write SHAPE by `test:bank-insert-writes`.
 * What is only observable HERE is the join between them:
 *
 *   - pressing Use opens the placement step and inserts NOTHING on its own;
 *   - confirming a position splices the paper's own copy in AT that position,
 *     so everything after it shifts down;
 *   - the copy carries provenance and lands unlocked and unedited;
 *   - the usage counter is bumped exactly once per insert, twice for two
 *     rapid inserts;
 *   - a question with nowhere to go gets a section added and inserted into it;
 *   - nothing in the flow writes to the bank.
 *
 * The drawer is stubbed down to two "use" buttons: what it renders is
 * QuestionBankBrowser's business, and mounting it here would make this a test
 * about the drawer instead of about the insert.
 */

