// The curriculum selector is mocked to a single button that, when clicked,
// hands the studio a fully-satisfied curriculum payload via its onChange — so
// onGenerate's standalone-mode guards pass without driving the real selector.
const VALID_CURR = {
  curriculumMode: 'cbc',
  grade: '4',
  subject: 'mathematics',
  subjectLabel: 'Mathematics',
  topic: 'Fractions',
  subtopic: 'Adding fractions',
  curriculum: 'cbc',
  framework: '2023',
}
vi.mock('../../../components/teacher/curriculum/StudioCurriculumSelector', () => ({
  default: ({ onChange }) => (
    <button type="button" onClick={() => onChange(VALID_CURR)}>
      seed-curriculum
    </button>
  ),
}))

function renderStudio() {
  return render(
    <MemoryRouter>
      <NotesStudio />
    </MemoryRouter>,
  )
}

// Satisfy the curriculum guards, then return the Generate button.
function seedCurriculumAndGetGenerate() {
  fireEvent.click(screen.getByRole('button', { name: /seed-curriculum/i }))
  return screen.getByRole('button', { name: /Generate Notes/i })
}

beforeEach(() => {
  vi.clearAllMocks()
})

afterEach(() => {
  // The lock persists its pending record to sessionStorage keyed by lockKey;
  // clear it so idempotency-key state never leaks across tests.
  sessionStorage.clear()
})

describe('NotesStudio — AI idempotency lock wiring', () => {
  it('sends a payload carrying a client-minted idempotencyKey when generating', async () => {
    const { generateNotes } = await import('../../../utils/teacherTools')
    generateNotes.mockResolvedValue({
      ok: true,
      data: { notes: { header: {} }, generationId: 'gen-1', usage: null, warning: '' },
    })

    renderStudio()
    const generateBtn = seedCurriculumAndGetGenerate()

    await act(async () => {
      fireEvent.click(generateBtn)
    })

    expect(generateNotes).toHaveBeenCalledTimes(1)
    const payload = generateNotes.mock.calls[0][0]
    expect(typeof payload.idempotencyKey).toBe('string')
    expect(payload.idempotencyKey).toBeTruthy()
    expect(payload.idempotencyKey).toMatch(UUID_RE)
    // Sanity: the seeded curriculum rode along in the payload.
    expect(payload.topic).toBe('Fractions')
  })

  it('a synchronous double-submit results in exactly one generateNotes call', async () => {
    const { generateNotes } = await import('../../../utils/teacherTools')
    // A deferred that stays pending, so BOTH clicks land while the first
    // request is still in flight — exactly when the lock has to hold.
    let resolveGenerate
    generateNotes.mockImplementation(
      () => new Promise((res) => { resolveGenerate = res }),
    )

    renderStudio()
    const generateBtn = seedCurriculumAndGetGenerate()

    // Two rapid clicks in the same synchronous burst — like a real double-click
    // firing before React re-renders the disabled state.
    fireEvent.click(generateBtn)
    fireEvent.click(generateBtn)

    expect(generateNotes).toHaveBeenCalledTimes(1)

    // Release the in-flight request so nothing dangles.
    await act(async () => {
      resolveGenerate({
        ok: true,
        data: { notes: { header: {} }, generationId: 'gen-1', usage: null, warning: '' },
      })
    })
    expect(generateNotes).toHaveBeenCalledTimes(1)
  })
})
