import NotesStudio from './NotesStudio.jsx'

// Request-locking / idempotency initiative — this suite is the UI-level
// guarantee for the Notes studio: (1) a real generation sends a payload
// carrying a client-minted idempotencyKey, and (2) a synchronous double-submit
// (two clicks before the first resolves) produces exactly ONE generateNotes
// call. useAiOperationLock + aiOperationLockCore run for real here — that's the
// wiring under test — everything else the component pulls in is mocked so the
// studio renders in jsdom and its Generate path can be driven. Mirrors
// HomeworkStudio.spec.jsx (standalone mode, seeded curriculum).

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

// The generator + the constant exports NotesStudio reads for its selects.
