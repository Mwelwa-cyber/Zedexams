/**
 * Put the word back into its sentence — what the learner sees once they get it
 * right, and what the guardian's report quotes.
 *
 * Capitalises when the gap LEADS the sentence. 46 of the sentences below start
 * with their own answer ("___ your arms before you start running"), which is
 * good English and would read as a typo if it were filled in verbatim. The
 * bank stores every word lowercase because that is what the letter tiles are;
 * the capital is a rendering decision and lives here, once.
 */
export function fillSentence(word, sentence) {
  if (!sentence || !word) return sentence || ''
  const leads = sentence.trimStart().startsWith('___')
  const shown = leads ? word.charAt(0).toUpperCase() + word.slice(1) : word
  return sentence.replace('___', shown)
}

/** The words of one band, in bank order. */
export function wordsInBand(bandId) {
  return SPELLING_BANK.filter((w) => w.band === bandId)
}

/** How many words each band holds — what the content-gap report reads. */
export function bandCounts() {
  const counts = {}
  for (const band of SPELLING_BANDS) counts[band.id] = 0
  for (const row of SPELLING_BANK) counts[row.band] += 1
  return counts
}
