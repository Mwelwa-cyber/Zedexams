/**
 * The Grade 7 spelling bank — the content the spelling game runs on.
 *
 * ONE GRADE, DELIBERATELY. The learner side of the app is open to Grade 7 and
 * nothing else (`LEARNER_GRADES` in src/config/curriculum.js), so there is no
 * `grade` field on a row: every word in this file is a Grade 7 word and
 * `SPELLING_GRADE` says so once. When another grade opens, the migration is to
 * add the field and split the bank — not to guess a grade per row now.
 *
 * BANDS, NOT DIFFICULTY NUMBERS. Words are grouped by WHAT MAKES THEM HARD —
 * silent letters, double letters, -ie/-ei, suffix rules — because that is how
 * spelling is actually taught, and it is what lets a stage be composed as a
 * pure function of (bank, learner pool, stage number). The band order below IS
 * the difficulty ladder.
 *
 * EVERY SENTENCE CARRIES THE WORD'S MEANING AND NEVER THE WORD. The gap is
 * `___`. A sentence that contained its own answer would turn the exercise into
 * copying, which is the one thing the game must not become — `test:spelling-bank`
 * fails on it.
 *
 * BRITISH SPELLING THROUGHOUT. ECZ marks British forms: colour, realise,
 * neighbour, favourite. Generated word lists drift American by default, so the
 * test checks every word and every sentence against a list of American forms.
 * `practise`/`practice` is deliberately NOT in that check — both are correct
 * British forms (verb / noun), so no word list can decide between them; they
 * are in the homophone band, where the sentence does the deciding.
 *
 * Generated from the per-band sources; edit those and re-run the builder, or
 * edit here and keep `test:spelling-bank` green. Either way the test is the
 * contract.
 */

