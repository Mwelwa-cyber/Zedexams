/**
 * The "break it up" coach data — where to CUT a word the learner just missed.
 *
 * Showing the correct spelling teaches almost nothing. This is the thing that
 * does: the word split into the chunks a speller actually holds in their head,
 * with the trap marked, a line saying why people get it wrong, and two or
 * three words the SAME cut solves — which is what turns one word into a rule.
 *
 * THIS IS CONTENT, NOT CODE, and it needs the same approval gate as notes.
 * Generated syllabification is wrong often enough to teach a child the wrong
 * break, and a weak mnemonic is worse than none, so `hook` is EMPTY unless it
 * is both true and memorable — 78 of the 79 entries below have none, and that
 * is the correct ratio rather than a gap to fill in.
 *
 * The cut depends on the word, never always syllables:
 *
 *   syllables   long words          nec | ess | ar | y
 *   root+affix  suffix rules        begin | n | ing
 *   trap        only one bit is hard  rec | ei | ve
 *   sound-out   phonetically regular  str | ee | t
 *   family      one pattern, many words  n | ight → light, right, fight
 *
 * `chunks.join('') === word` exactly, and `test:spelling-bank` fails if it
 * ever stops being true — a cut that does not rebuild the word is a cut that
 * teaches a misspelling.
 *
 * COVERAGE IS DELIBERATELY PARTIAL. Only words a cut actually helps are here;
 * a regular word does not need chopping, and the game falls back to showing
 * the correct spelling when a word has no entry. Adding a word is a content
 * decision, not a code change.
 */

