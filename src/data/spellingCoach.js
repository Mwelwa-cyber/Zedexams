/** The coach entry for a word, or null when the word has no authored cut. */
export function coachFor(word) {
  return SPELLING_COACH[word] || null
}

/**
 * Validate one coach entry — the check the authoring tool runs on save.
 *
 * Returns a list of problems; an empty list means the entry is publishable.
 * Exported rather than inlined so the authoring screen and the test run the
 * SAME rules, which is the only way "validated on save" means anything.
 */
export function validateCoachEntry(word, entry) {
  const problems = []
  if (!entry) return ['no coach entry']
  if (!Array.isArray(entry.chunks) || entry.chunks.length === 0) problems.push('no chunks')
  else if (entry.chunks.join('') !== word) problems.push(`chunks rebuild "${entry.chunks.join('')}", not "${word}"`)
  if (entry.trap !== null && !(Number.isInteger(entry.trap) && entry.trap >= 0 && entry.trap < (entry.chunks?.length ?? 0))) {
    problems.push(`trap ${entry.trap} is out of range`)
  }
  if (!COACH_STRATEGIES.includes(entry.strategy)) problems.push(`unknown strategy "${entry.strategy}"`)
  if (entry.hook && !entry.hookNote) problems.push('hook with no hookNote')
  if (!entry.why) problems.push('no "why people get it wrong" line')
  if (entry.transfer?.includes(word)) problems.push('transfer list contains the word itself')
  return problems
}
