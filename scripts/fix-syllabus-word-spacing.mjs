// scripts/fix-syllabus-word-spacing.mjs
//
// Repairs spurious intra-word spaces in the Syllabi Studio curriculum data.
//
// The national CDC syllabi were extracted from PDFs, and that extraction
// scattered single spaces *inside* words — "Communicating" became
// "Communicatin g", "Form" became "F orm", "and" became "a nd", "solve"
// became "s olve". In the Syllabi Studio table (src/components/teacher/
// SyllabiLibrary.jsx, which renders public/syllabi/curriculum-data*.json)
// these read as words broken apart mid-letter, hurting readability. The
// same JSON also feeds the server-side CBC context, so fixing it at the
// source improves both surfaces at once.
//
// HOW THE FIX SET WAS DERIVED (and why it is safe):
//   Every fix is an explicit, reviewed [broken -> joined] pair. They were
//   generated by scanning the data for adjacent letter-runs separated by a
//   single space where one run is a <=2-char shard, validated against an
//   English dictionary so the join only fires when it reconstructs a real
//   word, and *only* when the pair is not already two legitimate words
//   (so genuine phrases like "in formation", "to a", "on a", "in human
//   beings", "Newton's law", "theme/s and title", "grade d" are left
//   untouched). Coincidental dictionary words that are NOT correct repairs
//   (e.g. "fungi and" -> "fungian") were excluded by hand. Function-word,
//   capitalised-command-word, and trailing-plural repairs that a pure
//   dictionary heuristic would skip were added after verifying each in
//   context. The net effect: only broken words are joined; no legitimate
//   content, structure, or formatting changes.
//
// Idempotent: re-running on already-clean data is a no-op. Applies to both
// the public asset and its functions/ deploy copy, and to both curriculum
// eras, keeping all four files byte-identical (the test:syllabus-data-sync
// guard asserts public/functions parity).
//
// Usage: node scripts/fix-syllabus-word-spacing.mjs

